const http = require('node:http');
const fs = require('node:fs');
const path = require('node:path');
const { pipeline } = require('node:stream');

const root = __dirname;
const musicFolder = path.join(root, 'music');
const audioPattern = /\.(mp3|wav|ogg|m4a|aac|flac|opus|webm)$/i;
function listTracks() {
  return fs.readdirSync(musicFolder, { withFileTypes: true })
    .filter(file => file.isFile() && audioPattern.test(file.name))
    .map(file => file.name).sort();
}

function createServer() {
  return http.createServer((req, res) => {
    if (!['GET', 'HEAD'].includes(req.method)) {
      res.writeHead(405, { Allow: 'GET, HEAD' }).end();
      return;
    }
    let pathname;
    try { pathname = decodeURIComponent(new URL(req.url, 'http://localhost').pathname); }
    catch { res.writeHead(400).end(); return; }
    if (pathname === '/api/music') {
      try {
        const body = JSON.stringify(listTracks());
        res.writeHead(200, { 'Content-Type': 'application/json', 'Cache-Control': 'no-store' });
        res.end(req.method === 'HEAD' ? undefined : body);
      } catch { res.writeHead(500).end(); }
      return;
    }
    // Serve public website assets only; never expose hidden files or server sources.
    const parts = pathname.split('/');
    if (parts.some(part => part.startsWith('.') || part.includes('\\') || part.includes(':') || part.includes('\0'))) {
      res.writeHead(403).end(); return;
    }
    const filename = pathname === '/' ? 'index.html' : pathname.slice(1);
    const mime = {
      '.html': 'text/html; charset=utf-8', '.js': 'text/javascript; charset=utf-8',
      '.css': 'text/css', '.png': 'image/png', '.jpg': 'image/jpeg', '.jpeg': 'image/jpeg',
      '.svg': 'image/svg+xml', '.ico': 'image/x-icon', '.mp3': 'audio/mpeg',
      '.wav': 'audio/wav', '.ogg': 'audio/ogg', '.m4a': 'audio/mp4',
      '.aac': 'audio/aac', '.flac': 'audio/flac', '.opus': 'audio/ogg', '.webm': 'audio/webm'
    }[path.extname(filename).toLowerCase()];
    if (!mime) { res.writeHead(404).end(); return; }
    const target = path.resolve(root, filename);
    if (!target.startsWith(root + path.sep)) { res.writeHead(403).end(); return; }
    let stat;
    try {
      // Do not allow symlinks to publish files outside this folder.
      if (!fs.realpathSync(target).startsWith(fs.realpathSync(root) + path.sep)) {
        res.writeHead(403).end(); return;
      }
      stat = fs.statSync(target);
      if (!stat.isFile()) throw new Error('Not a file');
    } catch { res.writeHead(404).end(); return; }
    const headers = { 'Content-Type': mime, 'Accept-Ranges': 'bytes', 'Cache-Control': 'no-cache' };
    let start = 0, end = stat.size - 1, code = 200;
    if (req.headers.range) {
      const range = /^bytes=(\d*)-(\d*)$/.exec(req.headers.range);
      if (range && (range[1] || range[2])) {
        start = range[1] ? Number(range[1]) : Math.max(0, stat.size - Number(range[2]));
        end = range[1] && range[2] ? Math.min(Number(range[2]), stat.size - 1) : stat.size - 1;
      } else { start = -1; }
      if (start < 0 || start > end || start >= stat.size) {
        res.writeHead(416, { 'Content-Range': 'bytes */' + stat.size }).end(); return;
      }
      code = 206;
      headers['Content-Range'] = 'bytes ' + start + '-' + end + '/' + stat.size;
    }
    headers['Content-Length'] = Math.max(0, end - start + 1);
    res.writeHead(code, headers);
    if (req.method === 'HEAD' || stat.size === 0) { res.end(); return; }
    pipeline(fs.createReadStream(target, { start, end }), res, () => {});
  });
}

if (require.main === module) {
  if (process.argv.includes('--index')) {
    const tracks = listTracks();
    fs.writeFileSync(path.join(musicFolder, 'tracks.js'),
      '// Generated by: node music-server.cjs --index\nwindow.GALLERY_TRACKS = ' + JSON.stringify(tracks, null, 2) + ';\n');
    console.log('Playlist updated: ' + tracks.length + ' song(s).');
  } else {
    const port = Number(process.env.PORT || 8080);
    const server = createServer();
    server.on('error', error => { console.error('Could not start gallery server: ' + error.message); process.exitCode = 1; });
    server.listen(port, '127.0.0.1', () => console.log('Open http://localhost:' + port + '/gallery.html (Ctrl+C to stop)'));
  }
}
module.exports = { createServer, listTracks };
